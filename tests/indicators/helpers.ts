import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect } from 'vitest';

const FIXTURES = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../fixtures');

export type Col = (number | null)[];

export interface Ohlcv {
  dates: string[];
  open: number[];
  high: number[];
  low: number[];
  close: number[];
  volume: number[];
}

function readCsv(file: string): { header: string[]; rows: string[][] } {
  const lines = readFileSync(file, 'utf8')
    .split('\n')
    .filter((l) => l.length > 0);
  const header = lines[0]!.split(',');
  return { header, rows: lines.slice(1).map((l) => l.split(',')) };
}

let cachedOhlcv: Ohlcv | undefined;

/** The 500-bar series generated by tests/fixtures/gen/gen_indicators.py. */
export function loadOhlcv(): Ohlcv {
  if (cachedOhlcv) return cachedOhlcv;
  const { header, rows } = readCsv(path.join(FIXTURES, 'ohlcv_500.csv'));
  const col = (name: string): string[] => {
    const idx = header.indexOf(name);
    if (idx < 0) throw new Error(`ohlcv_500.csv has no column ${name}`);
    return rows.map((r) => r[idx]!);
  };
  cachedOhlcv = {
    dates: col('date'),
    open: col('open').map(Number),
    high: col('high').map(Number),
    low: col('low').map(Number),
    close: col('close').map(Number),
    volume: col('volume').map(Number),
  };
  return cachedOhlcv;
}

/** Golden CSV -> columns keyed by header name; blank cell -> null. */
export function loadGolden(name: string): Record<string, Col> {
  const { header, rows } = readCsv(path.join(FIXTURES, 'golden', `${name}.csv`));
  const out: Record<string, Col> = {};
  header.forEach((h, c) => {
    if (h === 'date') return;
    out[h] = rows.map((r) => (r[c] === '' || r[c] === undefined ? null : Number(r[c])));
  });
  return out;
}

export function firstNonNull(xs: readonly (number | null)[]): number {
  return xs.findIndex((x) => x !== null);
}

/**
 * Asserts `actual` equals `expected` at every index where both are non-null (|a - e| <= tol * max(1, |e|)), and
 * that the null / non-null pattern is identical.
 */
export function expectSeriesClose(
  actual: readonly (number | null)[],
  expected: readonly (number | null)[],
  label: string,
  tol = 1e-6,
): void {
  expect(actual.length, `${label}: length`).toBe(expected.length);
  const patternMismatches: string[] = [];
  const valueMismatches: string[] = [];
  let compared = 0;
  for (let i = 0; i < expected.length; i++) {
    const a = actual[i];
    const e = expected[i];
    if ((a === null) !== (e === null)) {
      patternMismatches.push(`[${i}] actual=${a} expected=${e}`);
      continue;
    }
    if (a === null || e === null) continue;
    compared++;
    if (!(Math.abs(a - e) <= tol * Math.max(1, Math.abs(e)))) valueMismatches.push(`[${i}] actual=${a} expected=${e}`);
  }
  expect(patternMismatches.slice(0, 5), `${label}: null pattern`).toEqual([]);
  expect(valueMismatches.slice(0, 5), `${label}: values`).toEqual([]);
  expect(compared, `${label}: compared points`).toBeGreaterThan(0);
}
