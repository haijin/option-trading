import type { Fund } from './model';

interface FundSeed {
  fin?: boolean;
  /** eps, book value, free cash flow, dividend per share */
  ps: [number, number, number, number];
  /** 5y ROE, 10y ROE, ROIC */
  ret: [number, number, number | null];
  /** gross, operating, net margin */
  mar: [number | null, number | null, number];
  /** operating cash flow / net income, capex / revenue */
  cash: [number, number];
  /** interest cover, interest-bearing debt / net income */
  safe: [number | null, number | null];
  /** revenue CAGR 5y, EPS CAGR 5y, share count change 5y */
  gr: [number, number, number];
  /** payout ratio, buyback yield */
  sh: [number, number];
  g: [number, number, number];
  pe: [number, number, number];
  hpe: [number, number];
  dg?: number;
  /** competence (1-5), management (1-5), years listed */
  own: [number, number, number];
  info?: 'A' | 'B';
}

const f = (s: FundSeed): Fund => ({
  fin: s.fin ?? false,
  eps: s.ps[0],
  bvps: s.ps[1],
  fcfps: s.ps[2],
  dps: s.ps[3],
  roe5: s.ret[0],
  roe10: s.ret[1],
  roic: s.ret[2],
  gm: s.mar[0],
  om: s.mar[1],
  nm: s.mar[2],
  ocf: s.cash[0],
  capex: s.cash[1],
  cov: s.safe[0],
  dni: s.safe[1],
  rc5: s.gr[0],
  ec5: s.gr[1],
  dil: s.gr[2],
  pay: s.sh[0],
  bb: s.sh[1],
  g: s.g,
  pe: s.pe,
  hpe: s.hpe,
  dg: s.dg,
  comp: s.own[0],
  mg: s.own[1],
  listed: s.own[2],
  info: s.info ?? 'A',
});

