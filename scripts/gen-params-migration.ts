/**
 * Writes a migration that inserts a new `default` strategy_params version from the current code defaults in
 * src/core/params.ts. Use it whenever a default changes: bump the version so live scoring and the skill-run cache
 * key change on purpose, and tests/db/migrations.test.ts keeps checking that the latest seeded version matches the code.
 *
 *   pnpm exec tsx scripts/gen-params-migration.ts <migrationIndex> <version> "<note>"
 *   e.g. pnpm exec tsx scripts/gen-params-migration.ts 9 2 "v2: HK dteMax 180 days (2026-10-13)"
 *
 * Then add the tag to drizzle/meta/_journal.json and copy the previous snapshot to a new one with a fresh id.
 */
import { writeFileSync } from 'node:fs';
import { defaultParams, paramsHash } from '../src/core/params';
import { stableStringify } from '../src/core/util';

const [idxArg, versionArg, note] = process.argv.slice(2);
const idx = Number(idxArg);
const version = Number(versionArg);
if (!Number.isInteger(idx) || !Number.isInteger(version) || version < 2 || !note) {
  console.error('usage: gen-params-migration.ts <migrationIndex> <version>=2.. "<note>"');
  process.exit(2);
}
const params = defaultParams();
const json = stableStringify(params).replace(/'/g, "''");
const tag = `${String(idx).padStart(4, '0')}_params_v${version}`;
const sql = `-- Params v${version} (generated by scripts/gen-params-migration.ts; do not edit by hand).
-- ${note.replace(/\n/g, ' ')}
INSERT INTO "strategy_params" ("name", "version", "params", "params_hash", "note")
VALUES ('default', ${version}, '${json}'::jsonb, '${paramsHash(params)}', '${note.replace(/'/g, "''")}')
ON CONFLICT ("name", "version") DO NOTHING;
`;
writeFileSync(new URL(`../drizzle/${tag}.sql`, import.meta.url), sql);
console.log(
  `wrote drizzle/${tag}.sql (hash ${paramsHash(params)}); now register "${tag}" in drizzle/meta/_journal.json`,
);
