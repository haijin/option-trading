/**
 * Writes drizzle/0001_seed_defaults.sql: the `default` v1 strategy_params row (from the defaults in
 * src/core/params.ts, i.e. docs/04-skills-spec.md) and the single portfolio_settings row (equity NULL).
 * tests/db/migrations.test.ts fails if the committed migration drifts from the code defaults.
 */
import { writeFileSync } from 'node:fs';
import { defaultParams, paramsHash } from '../src/core/params';
import { stableStringify } from '../src/core/util';

const params = defaultParams();
const json = stableStringify(params).replace(/'/g, "''");
const sql = `-- Seeds (generated by scripts/gen-seed-migration.ts; do not edit by hand).
INSERT INTO "strategy_params" ("name", "version", "params", "params_hash", "note")
VALUES ('default', 1, '${json}'::jsonb, '${paramsHash(params)}', 'Defaults from docs/04-skills-spec.md')
ON CONFLICT ("name", "version") DO NOTHING;
--> statement-breakpoint
INSERT INTO "portfolio_settings" ("id") VALUES (1) ON CONFLICT ("id") DO NOTHING;
`;
writeFileSync(new URL('../drizzle/0001_seed_defaults.sql', import.meta.url), sql);
console.log('wrote drizzle/0001_seed_defaults.sql');
